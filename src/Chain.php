final class Chain implements Stringable
{
    /** @var array<string, string|null> The verb each method name runs, or null. */
    private static array $verbs = [];

    public function __construct(private readonly Table $table) {}

    /** The table at this point in the chain. */
    public function get(): Table
    {
        return $this->table;
    }

    /**
     * Apply callables in order, as pipe() does: ->pipe(fn ($t) => ...).
     * A table result continues the chain.
     */
    public function pipe(callable ...$steps): mixed
    {
        return self::wrap(pipe($this->table, ...$steps));
    }

    /** @param array<int|string, mixed> $args */
    public function __call(string $name, array $args): mixed
    {
        $verb = self::verb($name);
        if ($verb === null) {
            throw new BadMethodCallException(self::rejection($name));
        }

        return self::wrap(('Phplyr\\'.$verb)(...$args)($this->table));
    }

    public function __toString(): string
    {
        return (string) $this->table;
    }

    private static function wrap(mixed $result): mixed
    {
        return $result instanceof Table ? new self($result) : $result;
    }

    /**
     * The verb $name runs, or null when it names none. A verb is a phplyr
     * function that returns a Closure taking the table, and a chain spells
     * it camelCase, so groupBy() resolves to group_by().
     */
    private static function verb(string $name): ?string
    {
        if (! \array_key_exists($name, self::$verbs)) {
            self::$verbs[$name] = self::resolve($name);
        }

        return self::$verbs[$name];
    }

    private static function resolve(string $name): ?string
    {
        // camelCase only: an underscore is the function's own spelling,
        // which a chain does not take.
        if (\preg_match('/^[A-Za-z][A-Za-z0-9]*$/', $name) !== 1) {
            return null;
        }
        $verb = self::snake($name);

        return \function_exists('Phplyr\\'.$verb)
            && (string) (new ReflectionFunction('Phplyr\\'.$verb))->getReturnType() === 'Closure'
            ? $verb
            : null;
    }

    /**
     * groupBy -> group_by, sliceMin -> slice_min, topN -> top_n. The
     * built-ins are called with a leading backslash because phplyr's own
     * string helpers shadow some of them inside this namespace.
     */
    private static function snake(string $name): string
    {
        return \strtolower(\preg_replace('/(?<!^)[A-Z]/', '_$0', $name) ?? $name);
    }

    /** group_by -> groupBy, for pointing a snake_case call at the chain. */
    private static function camel(string $name): string
    {
        return \lcfirst(\str_replace('_', '', \ucwords($name, '_')));
    }

    private static function rejection(string $name): string
    {
        $message = "{$name}() is not a phplyr verb";
        if (\str_contains($name, '_') && self::verb(self::camel($name)) !== null) {
            return $message.'; a chained verb is camelCase, so write '.self::camel($name).'()';
        }

        return $message;
    }
}
